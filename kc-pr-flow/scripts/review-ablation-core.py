#!/usr/bin/env python3
"""Computation core for review-ablation.sh — arm building and the joint statistic.

review-ablation.sh owns the CLI, the receipt/manifest guards, and the jq work.
This file owns the two parts that need real computation:

  arm    resolve the enumerated span table against a baseline tree, apply an
         ablation, and prove it took effect by VERBATIM SPAN MATCH against the
         enumerated spec.
  stats  the pre-registered decision rule: single-step Westfall-Young max-T over
         the full C(2N,N)^M label-assignment space.

Stdlib only. Python 3.8+ and jq are already kc-pr-flow runtime dependencies
(review-runtime-safe-io.py), so this adds none.

WHY THE POST-CONDITION CHECKS THE SPEC, NOT THE PATCH
-----------------------------------------------------
The span set checked after an ablation is the ENUMERATED SPEC — every CUT span
the table names — never the set of spans the builder happened to apply. Checking
only what was applied asks the builder to grade its own homework: it agrees with
itself by construction and cannot fail. That is the same defect shape as proving
absence with the keywords you chose to grep for, and it is why the keyword grep
below is a canary rather than the proof: of the 10 CUT spans, four (S2, S3, S4,
S10) contain none of the four keyword patterns, so an arm that removed only the
keyword-bearing spans would leave the gate's failure-class table, its demotion
rule, its framework-meta sub-rule and the entire per-agent instruction blockquote
on disk while the keyword post-condition reported it clean.
"""

